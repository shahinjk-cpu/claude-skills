"""Set up and index mockup libraries.

A library is one named, persistent set of ads (say "My drafts" or "Acme competitors")
with its own ads.json, its own source media and its own viewer. Libraries sit side by
side in a library root, `./meta-ads/` by default:

    meta-ads/
      index.html        generated: the library home page (open this to pick a library)
      libraries.js      generated: the list of libraries, read by the home page and viewers
      <library>/
        ads.json        the library's spec; you and the user edit this
        assets/         source images and videos for this library (paths in ads.json point here)
        inventory.*     written by check.py
        viewer/         generated by render.py: index.html, data.js, media/, embed/, png/. Safe to delete.
        exports/        files made to send: share.py's .html, deck.py's .pdf/.pptx

Usage:
    python library.py new "Acme competitors" [--root DIR]   create a library folder
    python library.py list [--root DIR]                      show the libraries and their state
    python library.py index [--root DIR]                     rebuild index.html + libraries.js
                                                             (after renaming or deleting a folder)

render.py renders a spec that sits in a library into <library>/viewer/ and refreshes
the index itself, so `index` is only needed after changing folders by hand.
"""
import argparse
import datetime as dt
import json
import re
import shutil
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

SKILL_DIR = Path(__file__).resolve().parent.parent
HOME_TEMPLATE = SKILL_DIR / "assets" / "libraries.html"
DEFAULT_ROOT = "meta-ads"
MANIFEST = "libraries.js"      # its presence marks a folder as a library root
SUMMARY = "summary.json"       # written by render.py into <library>/viewer/


def slug(s):
    s = re.sub(r"[^A-Za-z0-9]+", "-", s or "library").strip("-").lower()
    return s[:60] or "library"


def is_root(folder):
    return (Path(folder) / MANIFEST).is_file()


def root_of(spec_path):
    """The library root a spec belongs to, or None. A spec is in a library when it sits
    directly in a folder whose parent is a library root (meta-ads/<library>/ads.json)."""
    parent = Path(spec_path).resolve().parent.parent
    return parent if is_root(parent) else None


def _read_json(p):
    try:
        with open(p, encoding="utf-8-sig") as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def scan(root):
    """Every library folder in root, from what's on disk (idempotent; deleted folders drop out)."""
    root = Path(root)
    libs = []
    for d in sorted(p for p in root.iterdir() if p.is_dir() and not p.name.startswith(".")):
        spec_file = d / "ads.json"
        summ = _read_json(d / "viewer" / SUMMARY)
        if not spec_file.exists() and not summ and not (d / "assets").is_dir():
            continue   # not a library (library.py new always creates assets/)
        spec = _read_json(spec_file) if spec_file.exists() else None
        camp = (spec or {}).get("campaign") if isinstance((spec or {}).get("campaign"), dict) else {}
        lib = {"id": d.name,
               "name": (summ or {}).get("name") or camp.get("name") or d.name,
               "notes": (summ or {}).get("notes") or camp.get("notes") or "",
               "rendered": bool(summ) and (d / "viewer" / "index.html").exists(),
               "has_spec": spec_file.exists()}
        if lib["rendered"]:
            for k in ("ads", "brands", "counts", "updated", "thumb", "thumb_color"):
                lib[k] = summ.get(k)
            if lib.get("thumb"):
                lib["thumb"] = f"{d.name}/viewer/{lib['thumb']}"
        elif isinstance(spec, dict):
            lib["ads"] = len(spec.get("ads") or [])
        # files made to send: share files, PDFs and PowerPoints (exports/, plus share/ from v1.4)
        found = [f for sub in ("exports", "share") if (d / sub).is_dir()
                 for f in (d / sub).iterdir() if f.suffix.lower() in (".html", ".pdf", ".pptx")]
        lib["exports"] = [f"{f.parent.name}/{f.name}" for f in sorted(found, key=lambda f: f.stat().st_mtime, reverse=True)]
        libs.append(lib)
    return libs


def write_index(root):
    """(Re)write libraries.js and the home page in root. Returns the library list."""
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    libs = scan(root)
    data = {"generated": dt.datetime.now().isoformat(timespec="seconds"), "libraries": libs}
    (root / MANIFEST).write_text("window.META_ADS_LIBRARIES = " + json.dumps(data, ensure_ascii=False) + ";\n",
                                 encoding="utf-8")
    shutil.copyfile(HOME_TEMPLATE, root / "index.html")
    return libs


def cmd_new(a):
    root = Path(a.root).resolve()
    folder = root / slug(a.name)
    if folder.exists():
        sys.exit(f"{folder} already exists. Pick another name, or add the ads to that library's ads.json.")
    (folder / "assets").mkdir(parents=True)
    write_index(root)
    print(f"Created library \"{a.name}\" at {folder}")
    print(f"  write its spec to   {folder / 'ads.json'}   (set campaign.name to \"{a.name}\")")
    print(f"  save its media in   {folder / 'assets'}")
    print(f"  then check and render that ads.json; the viewer goes to {folder / 'viewer'}")


def cmd_list(a):
    root = Path(a.root).resolve()
    if not is_root(root):
        sys.exit(f"No library root at {root} (no {MANIFEST}). Create a library with: library.py new NAME")
    libs = write_index(root)
    if not libs:
        print(f"{root}: no libraries yet")
        return
    print(f"Libraries in {root}:")
    for l in libs:
        if l["rendered"]:
            c = l.get("counts") or {}
            state = f"{l.get('ads', 0)} ads, {c.get('actual', 0)} actual + {c.get('simulated', 0)} simulated mockups, rendered {l.get('updated', '')}"
        elif l["has_spec"]:
            state = f"{l.get('ads', 0)} ads, not rendered yet"
        else:
            state = "empty (no ads.json yet)"
        print(f"  {l['id']:<28} {l['name']}  ({state})")
    print(f"  home page: {root / 'index.html'}")


def cmd_index(a):
    root = Path(a.root).resolve()
    if not root.is_dir():
        sys.exit(f"{root} does not exist")
    libs = write_index(root)
    print(f"Indexed {len(libs)} librar{'y' if len(libs) == 1 else 'ies'} in {root}; home page: {root / 'index.html'}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name, fn, hlp in (("new", cmd_new, "create a library"), ("list", cmd_list, "list libraries"),
                          ("index", cmd_index, "rebuild the home page and library list")):
        p = sub.add_parser(name, help=hlp)
        if name == "new":
            p.add_argument("name", help='display name, e.g. "Acme competitors"')
        p.add_argument("--root", default=DEFAULT_ROOT, help=f"library root folder (default ./{DEFAULT_ROOT})")
        p.set_defaults(fn=fn)
    a = ap.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
